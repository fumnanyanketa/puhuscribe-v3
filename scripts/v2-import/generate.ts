// Turns the copied v2 files, the corrections file and the fixtures into load
// SQL (job 3-data-model, "Done when" 15 and 16). build.ts writes the results to
// disk; the tests in generate.test.ts compare them with the committed files.
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  applyCorrections,
  CORRECTIONS_FILE,
  gitBlobHash,
  IPA_COUNT,
  IPA_LICENCE,
  IPA_SOURCE,
  ipaFingerprint,
  parseCorrections,
  parseIpaMigration,
  parseStarterSeed,
  renderIpaLoad,
  renderSentenceLoad,
  sentenceFingerprint,
  STARTER_COUNT,
  STARTER_SOURCE,
  V2_COMMIT,
  V2_FILES,
} from './v2-starter.ts'

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
export const IPA_MIGRATION = 'supabase/migrations/20261020090300_load_v2_lemma_ipa.sql'
export const FIXTURE = {
  seed: 'scripts/v2-import/fixtures/v2-seed.fixture.sql',
  corrections: 'scripts/v2-import/fixtures/corrections.fixture.tsv',
  load: 'scripts/v2-import/fixtures/load.fixture.sql',
  source: 'fixture-v2-starter',
  count: 3,
}

const GENERATED =
  'GENERATED by scripts/v2-import/build.ts. Do not edit by hand: change the script and run it again.'

/** Reads the copy of a v2 file and proves it is byte for byte the file at the pinned commit. */
export function readV2Copy(which: keyof typeof V2_FILES): string {
  const file = V2_FILES[which]
  const bytes = readFileSync(join(ROOT, file.copy))
  const blob = gitBlobHash(bytes)
  if (blob !== file.blob) {
    throw new Error(
      `${file.copy} is not v2's ${file.v2Path} at ${V2_COMMIT} (blob ${blob}, want ${file.blob})`,
    )
  }
  return bytes.toString('utf8')
}

export function ipaMigrationText(): string {
  const entries = parseIpaMigration(readV2Copy('ipa'))
  if (entries.length !== IPA_COUNT)
    throw new Error(`Expected ${String(IPA_COUNT)} IPA rows, found ${String(entries.length)}`)
  return renderIpaLoad(entries, [
    'Job 3-data-model ("Done when" 16): pronunciation (IPA) for 514 Finnish base forms, from PuhuScribe v2.',
    GENERATED,
    `Source: v2 commit ${V2_COMMIT},`,
    `  ${V2_FILES.ipa.v2Path}`,
    `  (copy: ${V2_FILES.ipa.copy}, git blob ${V2_FILES.ipa.blob}).`,
    `Data: ${IPA_SOURCE}, ${IPA_LICENCE}. Showing it to learners needs that attribution line.`,
    'Reference only: no learner can read lemma_ipa. An upsert keyed on the lemma, so running it',
    'again changes nothing. The database check runs it a second time on purpose.',
    `Fingerprint checked by supabase/tests/database/data_model_reference.test.sql: ${ipaFingerprint(entries)}`,
  ])
}

export function fixtureLoadText(): string {
  const sentences = parseStarterSeed(readFileSync(join(ROOT, FIXTURE.seed), 'utf8'))
  if (sentences.length !== FIXTURE.count) throw new Error(`Expected ${String(FIXTURE.count)} fixture rows`)
  const corrected = applyCorrections(
    sentences,
    parseCorrections(readFileSync(join(ROOT, FIXTURE.corrections), 'utf8')),
  )
  return renderSentenceLoad(corrected, {
    source: FIXTURE.source,
    origin: `made-up fixture ${FIXTURE.seed}`,
    correctionsFile: FIXTURE.corrections,
    header: [
      'Made-up fixture data for the starter sentence loader (job 3-data-model, "Done when" 15).',
      GENERATED,
      `Input: ${FIXTURE.seed} and ${FIXTURE.corrections}.`,
      'Run twice, then rolled back, by scripts/v2-import/fixtures/check-load-twice.sql in the database check.',
      `Fingerprint after corrections: ${sentenceFingerprint(corrected)}`,
    ],
  })
}

export function starterLoadText(): string {
  const sentences = parseStarterSeed(readV2Copy('sentences'))
  if (sentences.length !== STARTER_COUNT) {
    throw new Error(`Expected ${String(STARTER_COUNT)} sentences, found ${String(sentences.length)}`)
  }
  const corrected = applyCorrections(
    sentences,
    parseCorrections(readFileSync(join(ROOT, CORRECTIONS_FILE), 'utf8')),
  )
  return renderSentenceLoad(corrected, {
    source: STARTER_SOURCE,
    origin: `v2 commit ${V2_COMMIT.slice(0, 7)} ${V2_FILES.sentences.v2Path}; native speaker review of 15 June 2026`,
    correctionsFile: CORRECTIONS_FILE,
    header: [
      'Job 3-data-model ("Done when" 15): v2\'s 104 starter sentences, with the native reviewer\'s corrections.',
      GENERATED,
      `Source: v2 commit ${V2_COMMIT},`,
      `  ${V2_FILES.sentences.v2Path}`,
      `  (copy: ${V2_FILES.sentences.copy}, git blob ${V2_FILES.sentences.blob}),`,
      `  with ${CORRECTIONS_FILE} applied.`,
      'Reference only: no learner can read source_sentences. A sentence reused in a unit is approved again',
      'by the reviewer in its dialogue. An upsert keyed on (source, source_ref), so running it again',
      'changes nothing.',
      `Fingerprint after corrections: ${sentenceFingerprint(corrected)}`,
    ],
  })
}
